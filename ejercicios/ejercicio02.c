#include <stdio.h>
#include <stdbool.h>

/*-----------------AUXILIARY FUNCTIONS--------------------*/
void readTwoIntegers(int *a, int *b)
{
    printf("Please, enter two int numbers: \n");
    scanf("%d %d", a, b);
}

int addTwoIntegers(int a, int b)
{
    return a + b;
}

int subtractTwoIntegers(int a, int b)
{
    return a - b;
}

int multiplyTwoIntegers(int a, int b)
{
    return a * b;
}

float divideTwoIntegers(int a, int b)
{
    return (float)a / b;
}

int maxOfTwoIntegers(int a, int b)
{
    if (a > b)
    {
        return a;
    }
    else
    {
        return b;
    }
}

bool isEven(int n)
{
    return n % 2 == 0;
}

int input(void)
{
    int number;
    printf("enter a number: ");
    scanf("%d", &number);
    return number;
}

// the purpose of this function is simply to print the output generated by the chosen option in the menu
void output(float number)
{
    printf("The output is: %.2f\n", number);
}
/*-----------------AUXILIARY FUNCTIONS--------------------*/

/*---------------------MAIN---------------------*/
int main(void)
{
    int choice, x, y;

    do
    {
        printf("\n===== MENU =====\n");
        printf("1. Add\n");
        printf("2. Subtract\n");
        printf("3. Multiply\n");
        printf("4. Divide\n");
        printf("5. Check if a number is even\n");
        printf("0. Exit\n");
        printf("Choose an option, ");
        choice = input();

        switch (choice)
        {
        // add
        case 1:
            readTwoIntegers(&x, &y);
            output(addTwoIntegers(x, y));
            break;

        // subtract
        case 2:
            readTwoIntegers(&x, &y);
            output(subtractTwoIntegers(x, y));
            break;

        // multiply
        case 3:
            readTwoIntegers(&x, &y);
            output(multiplyTwoIntegers(x, y));
            break;

        // divide
        case 4:
            readTwoIntegers(&x, &y);
            if (y == 0)
            {
                printf("Error: cannot divide by 0\n");
            }
            else
            {
                output(divideTwoIntegers(x, y));
            }
            break;

        // check if a number is even
        case 5:
            x = input();
            if (isEven(x))
            {
                printf("%d is even\n", x);
            }
            else
            {
                printf("%d is odd\n", x);
            }
            break;

        case 0:
            printf("exiting program...\n");
            break;

        default:
            printf("Wrong input\n");
            break;
        }
    } while (choice != 0);

    return 0;
}